const {expect}=require('chai');
const {ethers,network,upgrades}=require('hardhat');
const {time}=require('@nomicfoundation/hardhat-network-helpers');
const fs=require('fs'),path=require('path');
const release=require('../scripts/governance/assembly_release.cjs');
const keeperModule=require('../keeper/execute.cjs');
const DAY=86400;
describe('Pinned governance release rehearsal 2026-10-05',function(){
 this.timeout(600000);
 it('deploys exact creation bytes locally, executes generated Timelock batch, and settles an NFT vote',async function(){
  expect(network.name).to.equal('hardhat');expect((await ethers.provider.getNetwork()).chainId).to.equal(31337n);
  const out=path.resolve(process.env.ASSEMBLY_REHEARSAL_OUT||'');
  const allowed=path.resolve(__dirname,'../../governance-operations/releases')+path.sep;
  if(!out.startsWith(allowed)||!fs.existsSync(path.join(out,'preflight.json')))throw Error('Prepared release directory required');
  const baseline=JSON.parse(fs.readFileSync(path.join(out,'preflight.json')));
  expect(network.config.forking.blockNumber).to.equal(baseline.preflight.block);
  const manifest=JSON.parse(fs.readFileSync(path.join(out,'reviewed-manifest.json')));release.verifyManifest(manifest);
  await network.provider.send('evm_mine');
  const [deployer,alice,bob,recipient,keeper]=await ethers.getSigners();
  const pin=release.PIN,gas={};
  const inspect={getNetwork:async()=>({chainId:8453n}),getBlockNumber:()=>ethers.provider.getBlockNumber(),getStorage:(...a)=>ethers.provider.getStorage(...a),getCode:(...a)=>ethers.provider.getCode(...a),call:(...a)=>ethers.provider.call(...a)};
  await release.preflight(inspect);
  await upgrades.validateUpgrade(await ethers.getContractFactory('AnnualGovernance'),await ethers.getContractFactory('AnnualGovernanceV2'),{kind:'uups'});
  async function create(label,data){const r=await(await deployer.sendTransaction({data,gasLimit:16000000})).wait();expect(r.status).to.equal(1);gas[label]=String(r.gasUsed);return r.contractAddress;}
  const vaultImpl=await create('deployAssemblyImplementation',release.artifact('OliveAssembly').a.bytecode);
  const plan=release.deploymentPlan(vaultImpl);
  const govImpl=await create('deployGovernanceImplementation',plan.implementations[1].data);
  const vaultAddress=await create('deployInitializedAssemblyProxy',plan.assemblyProxy.data);
  const vault=await ethers.getContractAt('OliveAssembly',vaultAddress),gov=await ethers.getContractAt('AnnualGovernanceV2',pin.governance);
  await release.preflight(inspect,{assembly:vaultAddress,implementation:govImpl});
  expect(await vault.owner()).to.equal(pin.owner);expect(await vault.oliveNFT()).to.equal(pin.nft);
  async function impersonate(a){await network.provider.send('hardhat_setBalance',[a,'0x56BC75E2D63100000']);return ethers.getImpersonatedSigner(a);}
  const safe=await impersonate(pin.voteAdmin),owner=await impersonate(pin.owner),tl=await ethers.getContractAt('OBNTimeLock',pin.owner);
  const generated=release.payloads(vaultAddress,govImpl,ethers.id('assembly-local-rehearsal-'+baseline.preflight.block));
  await(await safe.sendTransaction(generated.schedule.transactions[0])).wait();
  await expect(safe.sendTransaction(generated.execute.transactions[0])).to.be.reverted;
  await time.increaseTo(await tl.getTimestamp(generated.operationId));
  const execution=await(await safe.sendTransaction(generated.execute.transactions[0])).wait();gas.upgradeAndBind=String(execution.gasUsed);
  expect(await tl.isOperationDone(generated.operationId)).to.equal(true);
  expect(await gov.nftVault()).to.equal(vaultAddress);expect(await vault.governance()).to.equal(pin.governance);
  expect(await gov.owner()).to.equal(pin.owner);expect(await gov.voteAdmin()).to.equal(pin.voteAdmin);
  const staking=await ethers.getContractAt('OBNStakingPoolsV931',pin.stakingPools),token=await ethers.getContractAt('OBNToken',pin.obn),nft=await ethers.getContractAt('OliveNFT',pin.nft);
  expect(await staking.version()).to.equal('9.3.1');expect(await nft.owner()).to.equal(pin.owner);
  expect(await nft.saleActive(),'public NFT mint open for realistic registration rehearsal').to.equal(true);
  const ids=[];
  for(const [i,voter]of [alice,bob].entries()){
   const minted=await(await nft.connect(voter).mint({value:await nft.MINT_PRICE()})).wait();
   const event=minted.logs.map(l=>{try{return nft.interface.parseLog(l);}catch{return null;}}).find(e=>e?.name==='Transfer'&&e.args.to===voter.address);ids.push(event.args.tokenId);
   await token.connect(safe).transfer(voter.address,ethers.parseEther(i===0?'1':'4'));
   await token.connect(voter).approve(pin.stakingPools,ethers.MaxUint256);
   await staking.connect(voter).deposit(0,ethers.parseEther(i===0?'1':'4'));
   await nft.connect(voter).approve(vaultAddress,ids[i]);
   const r=await(await vault.connect(voter).deposit(ids[i])).wait();gas['register'+i]=String(r.gasUsed);
  }
  expect(await vault.registeredCount()).to.equal(2);
  const offeringBefore=await token.balanceOf(pin.theOffering),extendBefore=await token.balanceOf(pin.extendOliveBranch);
  const start=await(await gov.connect(safe).startAnnualCycle(30*DAY,30*DAY)).wait();gas.start=String(start.gasUsed);
  expect(await gov.getCycleFundSnapshot(1)).to.deep.equal([offeringBefore,extendBefore,true]);
  expect((await gov.getCycleSummary(1)).phase1End-BigInt((await ethers.provider.getBlock(start.blockNumber)).timestamp)).to.equal(BigInt(30*DAY));
  await expect(gov.connect(owner).upgradeToAndCall(govImpl,'0x')).to.be.reverted;
  await expect(vault.connect(owner).upgradeToAndCall(vaultImpl,'0x')).to.be.reverted;
  await vault.connect(alice).withdrawExpected(ids[0],recipient.address);
  await staking.connect(alice).withdraw(0,ethers.parseEther('1'));
  expect(await nft.ownerOf(ids[0])).to.equal(recipient.address);
  expect((await gov.getVotingPowerForCycle(1,alice.address))[0]).to.equal(ethers.parseEther('1'));
  for(const voter of [alice,bob])await gov.connect(voter).castOfferingVote(1,false);
  await expect(gov.connect(alice).castOfferingVote(1,true)).to.be.reverted;
  await token.connect(safe).transfer(pin.theOffering,ethers.parseEther('17'));
  await token.connect(safe).transfer(pin.extendOliveBranch,ethers.parseEther('23'));
  const retainedOffering=(await token.balanceOf(pin.theOffering))-offeringBefore;
  const retainedExtend=(await token.balanceOf(pin.extendOliveBranch))-extendBefore;
  expect((await keeperModule.executeCycle(inspect,gov,keeper,false)).action).to.equal('nothing-ready');
  await time.increaseTo((await gov.getCycleSummary(1)).phase1End);
  expect((await keeperModule.executeCycle(inspect,gov,keeper,true)).action).to.equal('executed');
  const phase2Start=await ethers.provider.getBlock('latest');
  expect((await gov.getCycleSummary(1)).phase2End).to.equal(BigInt(phase2Start.timestamp+30*DAY));
  expect(await gov.getPhase2Allocation(1)).to.deep.equal([offeringBefore+extendBefore,true]);
  const ballot=await gov.getBallotPage(1,0,100),winner=ballot[0];expect(ballot.length).to.equal(baseline.preflight.ballotSize);
  for(const voter of [alice,bob])await gov.connect(voter).castNonprofitVote(1,winner);
  const winnerBefore=await token.balanceOf(winner);
  await time.increaseTo((await gov.getCycleSummary(1)).phase2End);
  expect((await keeperModule.executeCycle(inspect,gov,keeper,true)).action).to.equal('executed');
  expect(await token.balanceOf(winner)).to.equal(winnerBefore+offeringBefore+extendBefore);
  expect(await token.balanceOf(pin.theOffering)).to.equal(retainedOffering);expect(await token.balanceOf(pin.extendOliveBranch)).to.equal(retainedExtend);
  expect(await gov.getCycleParticipation(1)).to.deep.equal([2n,2n,2n,ethers.parseEther('3'),true]);
  await token.connect(safe).transfer(bob.address,ethers.parseEther('5'));await staking.connect(bob).deposit(0,ethers.parseEther('5'));
  await gov.connect(safe).startAnnualCycle(30*DAY,30*DAY);
  expect((await gov.getVotingPowerForCycle(2,alice.address))[0]).to.equal(0);
  expect((await gov.getVotingPowerForCycle(2,bob.address))[0]).to.equal(ethers.parseEther('3'));
  expect(await vault.registeredTokenId(bob.address)).to.equal(ids[1]);
  release.verifyManifest(manifest);
  const result={status:'PASSED - LOCAL FORK ONLY',forkBlock:baseline.preflight.block,chainId:31337,mainnetTransactions:0,localAddresses:{vaultImpl,govImpl,vaultAddress},generatedOperationId:generated.operationId,localPayloads:{targets:generated.targets,datas:generated.datas},gas,checks:['exact creation bytes and atomic proxy initialization','reviewed live V931 dependency retained','generated Timelock schedule/execute with delay','public NFT mint and registration','one- and four-OBN qualification','active-cycle upgrade guards','alternate-recipient withdrawal','post-snapshot stake/NFT withdrawals preserve this vote','permissionless keeper both phases','both phases exactly 30 days','later fund receipts retained','persistent registration with changed next-cycle power'],warning:'Simulation addresses and payloads are NOT production deployment addresses. Do not import into Safe.'};
  fs.writeFileSync(path.join(out,'rehearsal-only.json'),JSON.stringify(result,null,2)+'\n',{flag:'wx'});
  console.log(JSON.stringify({status:result.status,forkBlock:result.forkBlock,gas}));
 });
});
